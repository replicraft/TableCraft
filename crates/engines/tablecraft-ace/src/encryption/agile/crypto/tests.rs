use super::*;

fn bytes<const N: usize>(text: &str) -> [u8; N] {
    let data: Vec<_> = text
        .as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|s| u8::from_str_radix(std::str::from_utf8(s).unwrap(), 16).unwrap())
        .collect();
    data.try_into().unwrap()
}

#[test]
fn aes_cbc_decrypts_nist_sp800_38a_vectors_without_unpadding() {
    // NIST SP 800-38A F.2 first blocks, not produced by this implementation.
    let iv = bytes::<16>("000102030405060708090a0b0c0d0e0f");
    let plaintext = bytes::<16>("6bc1bee22e409f96e93d7e117393172a");
    for (key, encrypted) in [
        (
            "2b7e151628aed2a6abf7158809cf4f3c",
            "7649abac8119b246cee98e9b12e9197d",
        ),
        (
            "8e73b0f7da0e6452c810f32b809079e562f8ead2522c6b7b",
            "4f021db243bc633d7178183a9fa071e8",
        ),
        (
            "603deb1015ca71be2b73aef0857d77811f352c073b6108d72d9810a30914dff4",
            "f58c4c04d6e5f1ba779eabfb5f7bfbd6",
        ),
    ] {
        let key: Vec<u8> = key
            .as_bytes()
            .as_chunks::<2>()
            .0
            .iter()
            .map(|b| u8::from_str_radix(std::str::from_utf8(b).unwrap(), 16).unwrap())
            .collect();
        let mut block = bytes::<16>(encrypted);
        decrypt(&key, &iv, &mut block).unwrap();
        assert_eq!(block, plaintext);
    }
}

#[test]
fn page_validation_budget_and_cancellation_preserve_ciphertext() {
    let decoder = AgilePageDecoder {
        key: Zeroizing::new([0; 32]),
        encoding_key: Zeroizing::new([0; 4]),
        params: CipherParameters {
            key_bits: 128,
            hash: AgileHashAlgorithm::Sha1,
            salt: [0; 16],
        },
        page_count: 3,
    };
    let mut page = [0x55; PAGE_BYTES];
    let original = page;
    let mut budget = ResourceBudget::new(1_000_000, 0, 1_000_000);
    for number in [0, 3, u32::MAX] {
        assert_eq!(
            decoder.decode_page(number, &mut page, &mut budget, &|| false),
            Err(InspectError::MalformedEncryption)
        );
    }
    assert_eq!(
        decoder.decode_page(1, &mut page[..PAGE_BYTES - 1], &mut budget, &|| false),
        Err(InspectError::MalformedEncryption)
    );
    assert_eq!(
        decoder.decode_page(1, &mut page, &mut budget, &|| true),
        Err(InspectError::Cancelled)
    );
    assert!(matches!(
        decoder.decode_page(1, &mut page, &mut ResourceBudget::new(0, 0, 1000), &|| {
            false
        }),
        Err(InspectError::Limit(_))
    ));
    assert_eq!(page, original);
    let calls = std::cell::Cell::new(0);
    assert_eq!(
        decoder.decode_page(1, &mut page, &mut budget, &|| {
            calls.set(calls.get() + 1);
            calls.get() > 1
        }),
        Err(InspectError::Cancelled)
    );
    assert_eq!(page, original);
}

#[test]
fn independent_jce_vectors_cover_unicode_passwords_mixed_parameters_and_sha1_key_padding() {
    // Generated by the original docs/testing/AgileCryptoVectors.java using JCE.
    // Different password/data settings catch accidental use of one for the other.
    let cases = [
        (
            AgileHashAlgorithm::Sha1,
            AgileHashAlgorithm::Sha512,
            192,
            256,
            "9633cc89f8ed92459d41232dedebf9cd",
            "5e9ba280d6c1527b68f3abb249caa8c6c6367051ffd436c72d5c3b7486c2bb36",
            "32a6d4bb51f96d952efc6fa05c64e8b12889e28bb35dbb2dceef6460166eb577",
            "a810b4d6d4071ee302fbddce25b69d8d",
        ),
        (
            AgileHashAlgorithm::Sha256,
            AgileHashAlgorithm::Sha384,
            128,
            192,
            "b849825dcd0a0b640c988b54fa4f0b57",
            "caf8cbca91b63655b50b890fdb0e558d3ba85f5ff2b7d5259ba9eb85ef23d0e3",
            "f48fba9df61a678dfd096cbba203b12fae7d1a505b73baa104823947b25a0b72",
            "4fbce58f3d567940b2fbe71c07f0697d",
        ),
        (
            AgileHashAlgorithm::Sha384,
            AgileHashAlgorithm::Sha256,
            256,
            128,
            "7b7e595a139b98d6b3bf79dca3894b1e",
            "d70cbb1eb1f7e7753c709b59d2f90a974405b8b0c3b3d580db524d64260f0f7f30493aff062c20b5dec36f0c754afeef",
            "77a2b8f1734a00342f774a9492bd1bb6",
            "674dca3ae3e7d7e92b900b17bfa69f60",
        ),
        (
            AgileHashAlgorithm::Sha512,
            AgileHashAlgorithm::Sha1,
            256,
            256,
            "9a9ca185d2210a4a45d776f8d7353adb",
            "7f96c25ad1824f93051a60e42d2c329ba3332f9e9d319f87b1334e5e394b01baa78c853f9b3f9afb703c03366525c6734d058b27ccf4444819ed34b9266ae41b",
            "b0c17ecf2e18cc7788d8fa93175651dcce929d12466e1692eacedd1acab94ee5",
            "a7892e0fbb4cffab5028beb43721d942",
        ),
    ];
    fn padded<const N: usize>(hex: &str) -> [u8; N] {
        let mut out = [0; N];
        for (slot, pair) in out.iter_mut().zip(hex.as_bytes().as_chunks::<2>().0) {
            *slot = u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap();
        }
        out
    }
    for (
        password_hash,
        data_hash,
        password_bits,
        data_bits,
        verifier,
        verifier_hash,
        key,
        page_prefix,
    ) in cases
    {
        let d = super::super::Descriptor {
            password: CipherParameters {
                key_bits: password_bits,
                hash: password_hash,
                salt: std::array::from_fn(|i| i as u8),
            },
            data: CipherParameters {
                key_bits: data_bits,
                hash: data_hash,
                salt: std::array::from_fn(|i| (i + 16) as u8),
            },
            spins: 1000,
            verifier: bytes(verifier),
            verifier_hash: padded(verifier_hash),
            key: padded(key),
            has_integrity: false,
        };
        let encryption = AgileEncryption {
            descriptor: d,
            encoding_key: Zeroizing::new([0x11, 0x22, 0x33, 0x44]),
            page_count: 3,
        };
        let mut budget = ResourceBudget::new(1_000_000, 0, 1_000_000);
        let decoder = encryption
            .unlock(Some("A😀é"), &mut budget, &|| false)
            .unwrap();
        let mut page = [0; PAGE_BYTES];
        page[..16].copy_from_slice(&bytes::<16>(page_prefix));
        decoder
            .decode_page(1, &mut page, &mut budget, &|| false)
            .unwrap();
        assert_eq!(page[..16], bytes::<16>("6bc1bee22e409f96e93d7e117393172a"));
        assert!(matches!(
            encryption.unlock(Some("A😀e\u{301}"), &mut budget, &|| false),
            Err(InspectError::IncorrectPassword)
        ));
    }
}
