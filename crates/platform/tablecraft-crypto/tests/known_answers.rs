use tablecraft_crypto::{
    CryptoError, Direction, HashAlgorithm, Rc4Stream, aes_cbc, aes_ecb, constant_time_eq, digest,
};

fn hex(text: &str) -> Vec<u8> {
    text.as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect()
}

#[test]
fn standard_abc_digest_answers_keep_exact_outputs_and_zero_tails() {
    for (algorithm, expected) in [
        (HashAlgorithm::Md5, "900150983cd24fb0d6963f7d28e17f72"),
        (
            HashAlgorithm::Sha1,
            "a9993e364706816aba3e25717850c26c9cd0d89d",
        ),
        (
            HashAlgorithm::Sha256,
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
        ),
        (
            HashAlgorithm::Sha384,
            "cb00753f45a35e8bb5a03d699ac65007272c32ab0eded1631a8b605a43ff5bed8086072ba1e7cc2358baeca134c825a7",
        ),
        (
            HashAlgorithm::Sha512,
            "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f",
        ),
    ] {
        let expected = hex(expected);
        let actual = digest(algorithm, &[b"a", b"", b"bc"]);
        assert_eq!(&actual[..expected.len()], expected);
        assert!(actual[expected.len()..].iter().all(|byte| *byte == 0));
        assert_eq!(*actual, *digest(algorithm, &[b"abc"]));
    }
}

#[test]
fn nist_aes_ecb_and_cbc_first_blocks_cover_all_three_key_widths() {
    // NIST SP800-38A F.1/F.2, not generated by this implementation.
    let plaintext = hex("6bc1bee22e409f96e93d7e117393172a");
    let iv: [u8; 16] = hex("000102030405060708090a0b0c0d0e0f").try_into().unwrap();
    for (key, ecb, cbc) in [
        (
            "2b7e151628aed2a6abf7158809cf4f3c",
            "3ad77bb40d7a3660a89ecaf32466ef97",
            "7649abac8119b246cee98e9b12e9197d",
        ),
        (
            "8e73b0f7da0e6452c810f32b809079e562f8ead2522c6b7b",
            "bd334f1d6e45f25ff712a214571fa5cc",
            "4f021db243bc633d7178183a9fa071e8",
        ),
        (
            "603deb1015ca71be2b73aef0857d77811f352c073b6108d72d9810a30914dff4",
            "f3eed1bdb5d2a03c064b5a7e3db181f8",
            "f58c4c04d6e5f1ba779eabfb5f7bfbd6",
        ),
    ] {
        let key = hex(key);
        let mut block = plaintext.clone();
        aes_ecb(&key, &mut block, Direction::Encrypt).unwrap();
        assert_eq!(block, hex(ecb));
        aes_ecb(&key, &mut block, Direction::Decrypt).unwrap();
        assert_eq!(block, plaintext);
        aes_cbc(&key, &iv, &mut block, Direction::Encrypt).unwrap();
        assert_eq!(block, hex(cbc));
        aes_cbc(&key, &iv, &mut block, Direction::Decrypt).unwrap();
        assert_eq!(block, plaintext);
    }
}

#[test]
fn cbc_chaining_and_rc4_stream_position_survive_segment_boundaries() {
    let key = hex("2b7e151628aed2a6abf7158809cf4f3c");
    let iv: [u8; 16] = hex("000102030405060708090a0b0c0d0e0f").try_into().unwrap();
    let mut bytes = hex("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e51");
    aes_cbc(&key, &iv, &mut bytes, Direction::Encrypt).unwrap();
    assert_eq!(
        bytes,
        hex("7649abac8119b246cee98e9b12e9197d5086cb9b507219ee95db113a917678b2")
    );
    let mut text = b"Plaintext".to_vec();
    let (first, second) = text.split_at_mut(4);
    let mut stream = Rc4Stream::new(b"Key").unwrap();
    stream.apply(first);
    stream.apply(&mut []);
    stream.apply(second);
    assert_eq!(text, hex("bbf316e8d940af0ad3"));
    Rc4Stream::new(b"Key").unwrap().apply(&mut text);
    assert_eq!(text, b"Plaintext");
}

#[test]
fn checked_geometry_fails_before_mutation_and_equality_keeps_length_semantics() {
    for key_bytes in [0, 1, 15, 17, 31, 33] {
        let key = vec![0; key_bytes];
        let mut block = [0xa7; 16];
        assert_eq!(
            aes_ecb(&key, &mut block, Direction::Encrypt),
            Err(CryptoError::KeyLength)
        );
        assert_eq!(
            aes_cbc(&key, &[0; 16], &mut block, Direction::Decrypt),
            Err(CryptoError::KeyLength)
        );
        assert_eq!(block, [0xa7; 16]);
    }
    for length in [1, 15, 17, 31] {
        let mut bytes = vec![0x9d; length];
        let original = bytes.clone();
        assert_eq!(
            aes_ecb(&[0; 16], &mut bytes, Direction::Encrypt),
            Err(CryptoError::BlockLength)
        );
        assert_eq!(
            aes_cbc(&[0; 16], &[0; 16], &mut bytes, Direction::Decrypt),
            Err(CryptoError::BlockLength)
        );
        assert_eq!(bytes, original);
    }
    assert!(matches!(Rc4Stream::new(&[]), Err(CryptoError::KeyLength)));
    assert!(matches!(
        Rc4Stream::new(&[0; 257]),
        Err(CryptoError::KeyLength)
    ));
    assert!(constant_time_eq(b"secret", b"secret"));
    assert!(!constant_time_eq(b"secret", b"secreu"));
    assert!(!constant_time_eq(b"secret", b"secret\0"));
    assert!(constant_time_eq(b"", b""));
}
